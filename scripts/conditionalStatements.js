/*
  FALSY é quando um valor é ocnsiderado false
  THUTHY é quando um valor é considerado verdadeiro
  em contextos onde um boolean é considerado obrigatório (condicionais e loopts)
*/

// FALSY EXEMPLOS
console.log(false ? "TRUE" : "FALSE");
console.log(0 ? "TRUE" : "FALSE");
console.log(-0 ? "TRUE" : "FALSE");
console.log("" ? "TRUE" : "FALSE");
console.log(null ? "TRUE" : "FALSE");
console.log(undefined ? "TRUE" : "FALSE");
console.log(NaN ? "TRUE" : "FALSE");
